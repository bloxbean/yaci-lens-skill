#!/usr/bin/env bash
# Regenerate reference/schema.md from the live catalog (tables, partition column, rows, size, columns).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
out=$here/../reference/schema.md
{
  echo "# Lake schema"
  echo
  echo "Generated by \`scripts/gen-schema.sh\` from the live catalog on $(date -u +%Y-%m-%d). Amounts are lovelace unless"
  echo "the column says \`_ada\`. Partition column: filter on it so DuckDB reads only matching files."
  echo
  "$here/query.sh" -csv "
SELECT t.table_name, coalesce(p.part, '') AS partition, s.record_count AS rows, round(s.file_size_bytes / 1e9, 2) AS gb,
       string_agg(c.column_name || ' ' || c.column_type, ', ' ORDER BY c.column_order) AS columns
FROM lake_meta.ducklake_table t
JOIN lake_meta.ducklake_table_stats s USING (table_id)
JOIN lake_meta.ducklake_column c ON c.table_id = t.table_id AND c.end_snapshot IS NULL AND c.parent_column IS NULL
LEFT JOIN (SELECT pi.table_id, any_value(cc.column_name) AS part
           FROM lake_meta.ducklake_partition_info pi
           JOIN lake_meta.ducklake_partition_column pc USING (partition_id, table_id)
           JOIN lake_meta.ducklake_column cc ON cc.table_id = pc.table_id AND cc.column_id = pc.column_id AND cc.end_snapshot IS NULL
           WHERE pi.end_snapshot IS NULL GROUP BY 1) p ON p.table_id = t.table_id
WHERE t.end_snapshot IS NULL AND s.record_count > 0
GROUP BY ALL ORDER BY t.table_name" | python3 -c '
import csv, sys
for row in csv.DictReader(sys.stdin):
    name, part, gb, cols = row["table_name"], row["partition"] or "none", row["gb"], row["columns"]
    rows = int(row["rows"])
    print("## `" + name + "`")
    print()
    print("Partition: **" + part + "** · " + format(rows, ",") + " rows · " + gb + " GB")
    print()
    print("Columns: " + ", ".join("`" + c.strip() + "`" for c in cols.split(", ")))
    print()
'
  echo "# Summary pack"
  echo
  echo "Small precomputed tables, one Parquet file each, rebuilt daily. Read them with"
  echo "\`FROM '<summary-url><name>.parquet'\` (\`getvariable('summary')\` holds the folder URL). Amounts are ADA (DOUBLE)."
  echo
  for name in epochs daily latest_blocks pools governance dreps staking_daily staking_epochs drep_epochs pool_meta drep_meta action_meta script_index tx_index about; do
    echo "## \`$name\`"
    echo
    printf 'Columns: '
    "$here/query.sh" -csv "SELECT string_agg(column_name || ' ' || column_type, ', ') FROM (DESCRIBE SELECT * FROM read_parquet(getvariable('summary') || '$name.parquet'))" | tail -1 | sed 's/^"//; s/"$//' | python3 -c 'import sys; print(", ".join("`" + c.strip() + "`" for c in sys.stdin.read().strip().split(", ")))'
    echo
  done
} > "$out"
echo "wrote $out"
